    public void clean(){
        jTextFieldDocument.setText("");
        jTextFieldName.setText("");
        jTextFieldPhone.setText("");
        jTablePerson.clearSelection();
        jButtonInsert.setEnabled(true);
        jButtonModify.setEnabled(false);
        jButtonDelete.setEnabled(false);
    }
