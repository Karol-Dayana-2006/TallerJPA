    private void jButtonInsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonInsertActionPerformed
        try {
            Person person = new Person();
            person.setDocument(Long.parseLong(jTextFieldDocument.getText().toUpperCase()));
            person.setPhone(jTextFieldPhone.getText().toUpperCase());
            person.setName(jTextFieldName.getText().toUpperCase());
            personController.insert(person);
            MessageUtils.showInfoMessage("Categoria creada exitosamente");
            fillTable();
            clean();
        }
        catch (Exception e) {
            MessageUtils.showErrorMessage(e.getMessage());
        }
    }//GEN-LAST:event_jButtonInsertActionPerformed

    private void jButtonDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteActionPerformed
        try {
            int option = JOptionPane.showConfirmDialog(rootPane, "Esta seguro de eliminar esta persona?",
                "Confirmacion", JOptionPane.YES_NO_OPTION);
            if(option == JOptionPane.YES_OPTION)
            {
                personController.delete(Long.parseLong(jTextFieldDocument.getText()));
                MessageUtils.showInfoMessage("Persona eliminada exitosamente");
                fillTable();
                clean();
            }

        }
        catch (Exception e) {
            MessageUtils.showErrorMessage(e.getMessage());
        }
    }//GEN-LAST:event_jButtonDeleteActionPerformed

    private void jButtonModifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonModifyActionPerformed
        try {
            Person person = new Person();
            person.setDocument(Long.parseLong(jTextFieldDocument.getText().toUpperCase()));
            person.setName(jTextFieldName.getText().toUpperCase());
            person.setPhone(jTextFieldPhone.getText().toUpperCase());
            personController.update(person);
            MessageUtils.showInfoMessage("Persona modificada exitosamente");
            fillTable();
            clean();
        }
        catch (Exception e) {
            MessageUtils.showErrorMessage(e.getMessage());
        }
    }//GEN-LAST:event_jButtonModifyActionPerformed

