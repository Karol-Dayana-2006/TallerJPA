    private void jTableArticleMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableArticleMouseClicked
        int rowSelected = jTableArticle.getSelectedRow();
        if(rowSelected != -1)
        {
            long idArticleSelected = Long.parseLong(jTableArticle.getValueAt(rowSelected, 0).toString());
            try {
                Article article = articlecontroller.findById(idArticleSelected);
                jTextFieldIdArticle.setText(String.valueOf(idArticleSelected));
                jTextFieldName.setText(article.getName());
                jTextFieldPhoto.setText(article.getPhoto());
                jTextFieldQuantity.setText(String.valueOf(article.getQuantity()));
                jTextFieldTechnicalSheet.setText(article.getTechnicalSheet());
                jComboBoxIdPresentation.getModel().setSelectedItem(article.getIdPresentation());
                jComboBoxIdCategory.getModel().setSelectedItem(article.getIdCategory());
                jComboBoxIdSupplier.getModel().setSelectedItem(article.getIdSupplier());
                
                jButtonInsert.setEnabled(false);
                jButtonDelete.setEnabled(true);
                jButtonModify.setEnabled(true);
            } 
            catch (Exception e) {
                MessageUtils.showErrorMessage(e.getMessage());
            }
        }
    }//GEN-LAST:event_jTableArticleMouseClicked

