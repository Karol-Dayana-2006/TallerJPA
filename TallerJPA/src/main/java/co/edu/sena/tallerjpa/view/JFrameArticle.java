    public void fillTable(){
        try {
            DefaultTableModel model = new DefaultTableModel();
            jTableArticle.setModel(model);
            model.addColumn("Id");
            model.addColumn("Nombre");
            model.addColumn("Cantidad");
            model.addColumn("URl foto");
            model.addColumn("Ficha tecnica");
            model.addColumn("ID Presentación");
            model.addColumn("ID Categoria");
            model.addColumn("ID Proveedor");
            
            String[] rows = new String[8];
            List <Article> articles = articlecontroller.findAll();
            for (Article article : articles) {
                rows[0] = String.valueOf(article.getIdArticle());
                rows[1] = article.getName();
                rows[2] = String.valueOf(article.getQuantity());
                rows[3] = article.getPhoto();
                rows[4] = article.getTechnicalSheet();
                rows[5] = String.valueOf(article.getIdPresentation());
                rows[6] = String.valueOf(article.getIdCategory());
                rows[7] = String.valueOf(article.getIdSupplier());
                model.addRow(rows);
            }
        } 
        catch (Exception e) {
            MessageUtils.showErrorMessage(e.getMessage());
        }
    }

