    private void jButtonInsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonInsertActionPerformed
        try {
            Article article = new Article();
            article.setIdArticle(Long.parseLong(jTextFieldIdArticle.getText().toUpperCase()));
            article.setName(jTextFieldName.getText().toUpperCase());
            article.setQuantity(Integer.parseInt(jTextFieldQuantity.getText().toUpperCase()));
            article.setPhoto(jTextFieldPhoto.getText().toUpperCase());
            article.setTechnicalSheet(jTextFieldTechnicalSheet.getText().toUpperCase());
            
            //FKs
            Presentation type = (Presentation) jComboBoxIdPresentation.getSelectedItem();
            article.setIdPresentation(type);
            
            Category type2 = (Category) jComboBoxIdCategory.getSelectedItem();
            article.setIdCategory(type2);
            
            Supplier type3 = (Supplier) jComboBoxIdSupplier.getSelectedItem();
            article.setIdSupplier(type3);
            
            articlecontroller.insert(article);
            MessageUtils.showInfoMessage("Articulo Creado exitosamente");
            fillTable();
            clean();
        }
        catch (Exception e) {
            MessageUtils.showErrorMessage(e.getMessage());
        }
    }//GEN-LAST:event_jButtonInsertActionPerformed

